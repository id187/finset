 await waiting.goto(base+'?screen=guided&examples=1');
 await waiting.locator('.core-cases button').first().click();
 await waiting.waitForFunction(()=>window.__coreRequests.some(r=>r.input?.case_id));
 const oldId=await waiting.evaluate(()=>window.__coreRequests.find(r=>r.input?.case_id).id);
 await waiting.getByRole('button',{name:'처음부터',exact:true}).click();
